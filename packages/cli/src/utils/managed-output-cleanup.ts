/** One guarded rewrite request: what to replace and with what. */
interface GuardedRewriteRequest {
  directory: string;
  name: string;
  directoryStat: FileIdentity;
  fileStat: FileIdentity;
  expectedContent: string;
  content: string;
  mode?: number;
}

async function guardedRewrite(
  request: GuardedRewriteRequest,
  onUnresolvedWorker?: () => void
): Promise<boolean> {
  const invocation = getWorkerSelfInvocation();
  if (invocation === undefined) {
    onUnresolvedWorker?.();
    return false;
  }
  const expectedHash = createHash('sha256').update(request.expectedContent).digest('hex');

  return new Promise((resolveResult) => {
    const child = spawn(
      invocation.executable,
      workerSpawnArgs(
        invocation,
        'rewrite',
        request.name,
        String(request.directoryStat.dev),
        String(request.directoryStat.ino),
        String(request.fileStat.dev),
        String(request.fileStat.ino),
        expectedHash,
        request.mode === undefined ? '' : String(request.mode)
      ),
      {
        cwd: request.directory,
        stdio: ['pipe', 'pipe', 'ignore'],
        windowsHide: true,
      }
    );
    let stdout = '';
    child.stdout.setEncoding('utf-8');
    child.stdout.on('data', (chunk: string) => {
      stdout += chunk;
    });
    child.on('error', () => {
      resolveResult(false);
    });
    child.on('close', (code) => {
      resolveResult(code === 0 && stdout === 'rewritten');
    });
    child.stdin.on('error', () => {
      resolveResult(false);
    });
    child.stdin.end(request.content);
  });
}

async function guardedCreate(
  directory: string,
  name: string,
  directoryStat: FileIdentity,
  content: string,
  mode: number
): Promise<boolean> {
  const invocation = getWorkerSelfInvocation();
  if (invocation === undefined) {
    return false;
  }
  return new Promise((resolveResult) => {
    const child = spawn(
      invocation.executable,
      workerSpawnArgs(
        invocation,
        'create',
        name,
        String(directoryStat.dev),
        String(directoryStat.ino),
        String(mode)
      ),
      {
        cwd: directory,
        stdio: ['pipe', 'pipe', 'ignore'],
        windowsHide: true,
      }
    );
    let stdout = '';
    child.stdout.setEncoding('utf-8');
    child.stdout.on('data', (chunk: string) => {
      stdout += chunk;
    });
    child.on('error', () => {
      resolveResult(false);
    });
    child.on('close', (code) => {
      resolveResult(code === 0 && stdout === 'created');
    });
    child.stdin.on('error', () => {
      resolveResult(false);
    });
    child.stdin.end(content);
  });
}

async function visitDirectory(
  directory: string,
  desiredFiles: Set<string>,
  dryRun: boolean,
  removed: string[],
  ancestorGuards: DirectoryGuard[],
  onUnresolvedWorker: () => void
): Promise<void> {
  const directoryHandle = await safeOpenDirectory(directory);
  if (!directoryHandle) return;
  const guards = [...ancestorGuards, { path: directory, handle: directoryHandle }];

  try {
    if (!(await directoryGuardsMatch(guards))) return;

    const entries = await readdir(directory, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));
    for (const entry of entries) {
      const entryPath = resolve(directory, entry.name);
      const entryStat = await safeLstat(entryPath);
      if (!entryStat || entryStat.isSymbolicLink()) continue;

      if (entryStat.isDirectory()) {
        await visitDirectory(entryPath, desiredFiles, dryRun, removed, guards, onUnresolvedWorker);
        continue;
      }

      if (!entryStat.isFile() || desiredFiles.has(entryPath)) continue;
      if (!(await isPromptScriptGenerated(entryPath))) continue;
      if (!(await directoryGuardsMatch(guards))) continue;

      if (dryRun) {
        removed.push(entryPath);
        continue;
      }

      const currentStat = await safeLstat(entryPath);
      if (
        currentStat?.isFile() &&
        !currentStat.isSymbolicLink() &&
        isSameFile(entryStat, currentStat) &&
        (await directoryGuardsMatch(guards))
      ) {
        const directoryStat = await directoryHandle.stat();
        if (
          await guardedUnlink(
            directory,
            entry.name,
            directoryStat,
            entryStat,
            undefined,
            onUnresolvedWorker
          )
        ) {
          removed.push(entryPath);
        }
      }
    }
  } finally {
    await directoryHandle.close();
  }
}

async function guardedUnlink(
  directory: string,
  name: string,
  directoryStat: FileIdentity,
  fileStat: FileIdentity,
  expectedContent?: string,
  onUnresolvedWorker?: () => void
): Promise<boolean> {
  const invocation = getWorkerSelfInvocation();
  if (invocation === undefined) {
    // Fail closed: without a resolvable self-invocation there is no way to
    // run the worker, and guarded operations never degrade to in-process
    // filesystem writes.
    onUnresolvedWorker?.();
    return false;
  }
  const expectedHash =
    expectedContent === undefined
      ? undefined
      : createHash('sha256').update(expectedContent).digest('hex');
  try {
    const result = await execFileAsync(
      invocation.executable,
      workerSpawnArgs(
        invocation,
        'unlink',
        name,
        String(directoryStat.dev),
        String(directoryStat.ino),
        String(fileStat.dev),
        String(fileStat.ino),
        ...(expectedHash === undefined ? [] : [expectedHash])
      ),
      {
        cwd: directory,
        encoding: 'utf-8',
        windowsHide: true,
      }
    );
    return result.stdout === 'removed';
  } catch {
    // Runtimes where the worker cannot be spawned (packaged binaries with a
    // broken executable path, restricted spawn environments) fall back to an
    // in-process guarded unlink that re-verifies the file identity immediately
    // before removing it. Only the unlink without expected content has this
    // fallback; everything else stays failed.
    if (expectedContent !== undefined) return false;
    return removeIfUnchanged(resolve(directory, name), fileStat);
  }
}

/**
 * Remove a file only when it is still a regular (non-symlink) file whose device
 * and inode match the previously observed identity. Used as an in-process
 * fallback when a child process cannot perform the cwd-relative guarded unlink.
 */
export async function removeIfUnchanged(
  entryPath: string,
  fileStat: FileIdentity
): Promise<boolean> {
  const current = await safeLstat(entryPath);
  if (!current?.isFile() || current.isSymbolicLink() || !isSameIdentity(current, fileStat)) {
    return false;
  }

  try {
    await unlink(entryPath);
  } catch (error: unknown) {
    /* v8 ignore next 2 -- unlink races with external removal between check and delete */
    if (isNodeError(error) && error.code === 'ENOENT') return false;
    throw error;
  }
  return true;
}

async function openAncestorDirectories(
  root: string,
  directory: string
): Promise<DirectoryGuard[] | undefined> {
  const relativePath = relative(root, directory);
  const segments = relativePath === '' ? [] : relativePath.split(/[\\/]+/);
  const paths = [root];
  let current = root;
  for (const segment of segments.slice(0, -1)) {
    current = resolve(current, segment);
    paths.push(current);
  }

  const guards: DirectoryGuard[] = [];
  for (const path of paths) {
    const handle = await safeOpenDirectory(path);
    if (!handle) {
      await closeDirectoryGuards(guards);
      return undefined;
    }
    guards.push({ path, handle });
    if (!(await directoryGuardsMatch(guards))) {
      await closeDirectoryGuards(guards);
      return undefined;
    }
  }
  return guards;
}

async function openOrCreateAncestorDirectories(
  root: string,
  file: string
): Promise<DirectoryGuard[] | undefined> {
  const relativePath = relative(root, file);
  if (relativePath.startsWith('..') || isAbsolute(relativePath)) {
    return undefined;
  }

  await mkdir(root, { recursive: true });
  const guards: DirectoryGuard[] = [];
  const rootHandle = await safeOpenDirectory(root);
  if (!rootHandle) return undefined;
  guards.push({ path: root, handle: rootHandle });

  let current = root;
  const segments = relativePath.split(/[\\/]+/).slice(0, -1);
  for (const segment of segments) {
    if (!(await directoryGuardsMatch(guards))) {
      await closeDirectoryGuards(guards);
      return undefined;
    }
    const parentStat = await guards.at(-1)!.handle.stat();
    if (!(await guardedMkdir(current, segment, parentStat))) {
      await closeDirectoryGuards(guards);
      return undefined;
    }
    current = resolve(current, segment);
    const handle = await safeOpenDirectory(current);
    if (!handle) {
      await closeDirectoryGuards(guards);
      return undefined;
    }
    guards.push({ path: current, handle });
  }

  return guards;
}

async function guardedMkdir(
  directory: string,
  name: string,
  directoryStat: FileIdentity
): Promise<boolean> {
  const invocation = getWorkerSelfInvocation();
  if (invocation === undefined) {
    return false;
  }
  try {
    const result = await execFileAsync(
      invocation.executable,
      workerSpawnArgs(
        invocation,
        'mkdir',
        name,
        String(directoryStat.dev),
        String(directoryStat.ino)
      ),
      {
        cwd: directory,
        encoding: 'utf-8',
        windowsHide: true,
      }
    );
    return result.stdout === 'ready';
  } catch {
    return false;
  }
}

async function closeDirectoryGuards(guards: DirectoryGuard[]): Promise<void> {
  for (const guard of [...guards].reverse()) {
    await guard.handle.close();
  }
}

/** Platform-optional open flags, probed on first use: 0 where the runtime lacks them. */
let openNofollowFlag: number | undefined;
let openDirectoryFlag: number | undefined;

async function safeOpenDirectory(path: string): Promise<FileHandle | undefined> {
  try {
    // Probed lazily (not at module load) so test doubles that replace
    // node:fs wholesale still load this module.
    openNofollowFlag ??= constants.O_NOFOLLOW ?? 0;
    openDirectoryFlag ??= constants.O_DIRECTORY ?? 0;
    return await open(path, constants.O_RDONLY | openDirectoryFlag | openNofollowFlag);
  } catch (error: unknown) {
    if (
      isNodeError(error) &&
      (error.code === 'ENOENT' || error.code === 'ENOTDIR' || error.code === 'ELOOP')
    ) {
      return undefined;
    }
    throw error;
  }
}

async function directoryGuardsMatch(guards: DirectoryGuard[]): Promise<boolean> {
  for (const guard of guards) {
    const pathStat = await safeLstat(guard.path);
    if (!pathStat?.isDirectory() || pathStat.isSymbolicLink()) return false;
    const handleStat = await guard.handle.stat();
    if (!isSameFile(pathStat, handleStat)) return false;
  }
  return true;
}

function isSameFile(
  left: Awaited<ReturnType<typeof lstat>>,
  right: Awaited<ReturnType<typeof lstat>>
): boolean {
  return left.dev === right.dev && left.ino === right.ino;
}

function isSameIdentity(
  stat: { dev: number | bigint; ino: number | bigint },
  identity: FileIdentity
): boolean {
  return stat.dev === identity.dev && stat.ino === identity.ino;
}

async function safeLstat(path: string): Promise<Awaited<ReturnType<typeof lstat>> | undefined> {
  try {
    return await lstat(path);
  } catch (error: unknown) {
    if (isNodeError(error) && error.code === 'ENOENT') return undefined;
    throw error;
  }
}

async function isPromptScriptGenerated(path: string, allowInlineMarker = false): Promise<boolean> {
  try {
    const content = await readFile(path, 'utf-8');
    const lines = content
      .replace(/^\uFEFF/, '')
      .split(/\r?\n/)
      .slice(0, 4);
    const candidateLines =
      lines[0] === '---'
        ? [lines[1]]
        : [lines[0], ...(lines[0]?.startsWith('# ') && lines[1] === '' ? [lines[2]] : [])];
    const hasStandardMarker = candidateLines.some(
      (line) =>
        line !== undefined && PROMPTSCRIPT_MARKER_PATTERNS.some((pattern) => pattern.test(line))
    );
    return hasStandardMarker || (allowInlineMarker && isPromptScriptOwnedHookOutput(path, content));
  } catch (error: unknown) {
    if (isNodeError(error) && error.code === 'ENOENT') return false;
    throw error;
  }
}

interface HookOwnershipScan {
  found: boolean;
  valid: boolean;
}

export function hasOnlyOwnedHookCommands(content: string): boolean {
  try {
    const parsed: unknown = JSON.parse(content);
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) return false;
    const hooks = (parsed as Record<string, unknown>)['hooks'];
    const scan = scanHookOwnership(hooks);
    return scan.found && scan.valid;
  } catch {
    return false;
  }
}

