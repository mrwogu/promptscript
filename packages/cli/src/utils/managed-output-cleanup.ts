export function isPromptScriptOwnedHookOutput(path: string, content: string): boolean {
  const normalizedPath = path.replaceAll('\\', '/');
  const contract = getHookOutputContract(normalizedPath);
  if (!contract) return false;

  try {
    const parsed: unknown = JSON.parse(content);
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
      return false;
    }
    const object = parsed as Record<string, unknown>;
    if (Object.keys(object).some((field) => !contract.fields.has(field))) {
      return false;
    }
    const scan = scanHookOwnership(object['hooks']);
    return scan.found && scan.valid;
  } catch {
    return false;
  }
}

export function isHookOutputPath(path: string): boolean {
  const normalized = path.replaceAll('\\', '/');
  return (
    getHookOutputContract(normalized) !== undefined || normalized.endsWith('.codex/config.toml')
  );
}

function getHookOutputContract(
  path: string
): (typeof OWNED_HOOK_OUTPUT_FIELDS)[number] | undefined {
  return OWNED_HOOK_OUTPUT_FIELDS.find((candidate) => path.endsWith(candidate.suffix));
}

export function mergePromptScriptHookOutput(
  path: string,
  existingContent: string,
  generatedContent: string
): string | undefined {
  if (!isHookOutputPath(path)) return undefined;

  const existing = parseJsonObject(existingContent);
  const generated = parseJsonObject(generatedContent);
  if (!existing || !generated) return undefined;

  const existingHooks = getJsonObject(existing['hooks']);
  const generatedHooks = getJsonObject(generated['hooks']);
  if (existing['hooks'] !== undefined && !existingHooks) return undefined;
  if (!generatedHooks) {
    const generatedFields = Object.keys(generated);
    if (
      !path.replaceAll('\\', '/').endsWith('.claude/settings.json') ||
      generatedFields.length !== 1 ||
      generatedFields[0] !== 'autoMode'
    ) {
      return undefined;
    }
    return JSON.stringify({ ...existing, ...generated }, null, 2) + '\n';
  }

  return (
    JSON.stringify(
      {
        ...existing,
        ...generated,
        hooks: mergeHookEvents(existingHooks ?? {}, generatedHooks),
      },
      null,
      2
    ) + '\n'
  );
}

export interface RemovedOwnedHooks {
  content: string;
  empty: boolean;
}

export function removePromptScriptOwnedCodexHooks(
  path: string,
  content: string
): RemovedOwnedHooks | undefined {
  if (!path.replaceAll('\\', '/').endsWith('.codex/config.toml')) {
    return undefined;
  }

  const lines = content.split('\n');
  const remaining: string[] = [];
  let removed = false;
  for (let index = 0; index < lines.length; ) {
    const eventMatch = lines[index]!.match(/^\s*\[\[hooks\.([A-Za-z][A-Za-z0-9]*)\]\]\s*$/);
    if (!eventMatch) {
      remaining.push(lines[index]!);
      index += 1;
      continue;
    }

    const event = eventMatch[1]!;
    const group: string[] = [];
    while (index < lines.length) {
      const line = lines[index]!;
      if (
        group.length > 0 &&
        /^\s*\[/.test(line) &&
        !new RegExp(`^\\s*\\[\\[hooks\\.${event}\\.hooks\\]\\]\\s*$`).test(line)
      ) {
        break;
      }
      group.push(line);
      index += 1;
    }

    if (isOwnedCodexHookGroup(group, event)) {
      removed = true;
    } else {
      remaining.push(...group);
    }
  }

  if (!removed) return undefined;
  const prunedContent = remaining.join('\n');
  return {
    content: prunedContent,
    empty: prunedContent.trim().length === 0,
  };
}

export function mergePromptScriptCodexConfig(
  existingContent: string,
  generatedContent: string
): string | undefined {
  const managedRootKey =
    /^\s*(?:(?:max_threads|max_depth|agents_file)|"(?:max_threads|max_depth|agents_file)"|'(?:max_threads|max_depth|agents_file)')\s*=/;
  const generatedLines = generatedContent.split('\n').filter((line) => line.trim().length > 0);
  if (
    generatedLines.length === 0 ||
    generatedLines.some((line) => !/^\s*(?:max_threads|max_depth|agents_file)\s*=\s*.+$/.test(line))
  ) {
    return undefined;
  }

  let insideTable = false;
  const preserved = existingContent.split('\n').filter((line) => {
    if (/^\s*\[/.test(line)) insideTable = true;
    return insideTable || !managedRootKey.test(line);
  });
  const preservedContent = preserved.join('\n').trim();
  return `${generatedLines.join('\n')}${preservedContent ? `\n\n${preservedContent}` : ''}\n`;
}

export function removePromptScriptOwnedHooks(
  path: string,
  content: string
): RemovedOwnedHooks | undefined {
  const contract = getHookOutputContract(path.replaceAll('\\', '/'));
  if (!contract) return undefined;

  const parsed = parseJsonObject(content);
  const hooks = parsed ? getJsonObject(parsed['hooks']) : undefined;
  if (!parsed || !hooks) return undefined;

  let removed = false;
  const remainingHooks: Record<string, unknown> = {};
  for (const [event, entries] of Object.entries(hooks)) {
    if (!Array.isArray(entries)) {
      remainingHooks[event] = entries;
      continue;
    }
    const pruned = pruneOwnedHookEntries(entries);
    if (pruned.removed) removed = true;
    const remaining = pruned.entries;
    if (remaining.length > 0) remainingHooks[event] = remaining;
  }
  if (!removed) return undefined;

  const remainingTopLevel = Object.keys(parsed).filter(
    (field) => field !== 'hooks' && !isDisposableHookMetadata(contract.suffix, field)
  );
  const empty = Object.keys(remainingHooks).length === 0 && remainingTopLevel.length === 0;
  return {
    content: JSON.stringify({ ...parsed, hooks: remainingHooks }, null, 2) + '\n',
    empty,
  };
}

function mergeHookEvents(
  existing: Record<string, unknown>,
  generated: Record<string, unknown>
): Record<string, unknown> {
  const merged: Record<string, unknown> = {};
  for (const [event, entries] of Object.entries(existing)) {
    if (!Array.isArray(entries)) {
      merged[event] = entries;
      continue;
    }
    const unowned = pruneOwnedHookEntries(entries).entries;
    if (unowned.length > 0) merged[event] = unowned;
  }
  for (const [event, entries] of Object.entries(generated)) {
    if (!Array.isArray(entries)) {
      merged[event] = entries;
      continue;
    }
    const previous = Array.isArray(merged[event]) ? merged[event] : [];
    merged[event] = [...previous, ...entries];
  }
  return merged;
}

function isOwnedHookEntry(value: unknown): boolean {
  const scan = scanHookOwnership(value);
  return scan.found && scan.valid;
}

interface PrunedHookEntries {
  entries: unknown[];
  removed: boolean;
}

function pruneOwnedHookEntries(entries: unknown[]): PrunedHookEntries {
  const remaining: unknown[] = [];
  let removed = false;

  for (const entry of entries) {
    const object = getJsonObject(entry);
    const handlers = object?.['hooks'];
    if (Array.isArray(handlers)) {
      const prunedHandlers = pruneOwnedHookEntries(handlers);
      if (prunedHandlers.removed) {
        removed = true;
        if (prunedHandlers.entries.length > 0) {
          remaining.push({ ...object, hooks: prunedHandlers.entries });
        }
        continue;
      }
    }

    if (isOwnedHookEntry(entry)) {
      removed = true;
    } else {
      remaining.push(entry);
    }
  }

  return { entries: remaining, removed };
}

function parseJsonObject(content: string): Record<string, unknown> | undefined {
  try {
    const parsed: unknown = JSON.parse(content);
    return getJsonObject(parsed);
  } catch {
    return undefined;
  }
}

function getJsonObject(value: unknown): Record<string, unknown> | undefined {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : undefined;
}

function isDisposableHookMetadata(suffix: string, field: string): boolean {
  return (
    field === 'version' &&
    (suffix === '.github/hooks/promptscript.json' || suffix === '.cursor/hooks.json')
  );
}

function isOwnedCodexHookGroup(lines: string[], event: string): boolean {
  let commandCount = 0;
  for (const line of lines) {
    const trimmed = line.trim();
    if (
      trimmed.length === 0 ||
      trimmed === `[[hooks.${event}]]` ||
      trimmed === `[[hooks.${event}.hooks]]` ||
      isTomlStringAssignment(trimmed, 'matcher') ||
      isTomlStringAssignment(trimmed, 'statusMessage') ||
      /^timeout\s*=\s*\d+\s*$/.test(trimmed) ||
      /^type\s*=\s*"command"\s*$/.test(trimmed)
    ) {
      continue;
    }

    const command = trimmed.match(/^(?:command|command_windows)\s*=\s*"(.*)"\s*$/);
    // Ownership contract: hook-adapters.ts (HOOK_OWNERSHIP_MARKER) appends the
    // marker as the final token of every emitted command; keep both in sync.
    if (!command || !/# promptscript-generated:[A-Za-z0-9._-]+$/.test(command[1]!)) {
      return false;
    }
    commandCount += 1;
  }
  return commandCount > 0;
}

function isTomlStringAssignment(line: string, field: string): boolean {
  if (!line.startsWith(field)) return false;
  let index = field.length;
  while (index < line.length && /\s/.test(line[index]!)) index++;
  if (line[index] !== '=') return false;
  index++;
  while (index < line.length && /\s/.test(line[index]!)) index++;
  if (line[index] !== '"' || line.at(-1) !== '"' || index === line.length - 1) {
    return false;
  }

  for (let valueIndex = index + 1; valueIndex < line.length - 1; valueIndex++) {
    if (line[valueIndex] === '\\') valueIndex++;
    else if (line[valueIndex] === '"') return false;
  }
  return true;
}

function scanHookOwnership(value: unknown): HookOwnershipScan {
  if (Array.isArray(value)) {
    return value.reduce<HookOwnershipScan>(
      (result, item) => {
        const itemScan = scanHookOwnership(item);
        return {
          found: result.found || itemScan.found,
          valid: result.valid && itemScan.valid,
        };
      },
      { found: false, valid: true }
    );
  }

  if (typeof value !== 'object' || value === null) {
    return { found: false, valid: true };
  }

  const object = value as Record<string, unknown>;
  const commands = ['command', 'commandWindows', 'command_windows', 'bash', 'powershell', 'windows']
    .map((field) => object[field])
    .filter((command): command is string => typeof command === 'string');
  if (typeof object['type'] === 'string' || commands.length > 0) {
    if (typeof object['type'] === 'string' && object['type'] !== 'command') {
      return { found: true, valid: false };
    }
    return {
      found: true,
      valid:
        Object.keys(object).every((field) => OWNED_COMMAND_FIELDS.has(field)) &&
        commands.length > 0 &&
        // Ownership contract: the marker must be the final token of the command
        // (see HOOK_OWNERSHIP_MARKER in packages/formatters/src/hook-adapters.ts).
        commands.every((command) => /# promptscript-generated:[A-Za-z0-9._-]+\s*$/.test(command)),
    };
  }

  if (Array.isArray(object['hooks'])) {
    const nested = scanHookOwnership(object['hooks']);
    if (
      nested.found &&
      !Object.keys(object).every((field) => field === 'matcher' || field === 'hooks')
    ) {
      return { found: true, valid: false };
    }
    return nested;
  }

  return scanHookOwnership(Object.values(object));
}

function isWithin(root: string, candidate: string): boolean {
  const relativePath = relative(root, candidate);
  return relativePath === '' || (!relativePath.startsWith('..') && !isAbsolute(relativePath));
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && 'code' in error;
}
