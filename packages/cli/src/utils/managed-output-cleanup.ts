/**
 * Resolve the managed output worker module path relative to this module.
 *
 * Published installs bundle the worker next to the main bundle
 * (dist/managed-output-worker.js); in development the TypeScript source
 * (src/managed-output-worker.ts) is spawned directly via Node type
 * stripping. Deno standalone binaries never use this path - they re-execute
 * the binary itself.
 */
function resolveWorkerModulePath(): string | undefined {
  const bundled = fileURLToPath(new URL('./managed-output-worker.js', import.meta.url));
  if (existsSync(bundled)) return bundled;
  const source = fileURLToPath(new URL('../managed-output-worker.ts', import.meta.url));
  return existsSync(source) ? source : undefined;
}

let cachedWorkerModulePath: string | undefined | null = null;

/**
 * Resolve how this process spawns the managed output worker. The worker
 * module path is resolved once; the invocation itself is resolved per
 * operation so the runtime and process.execPath are read fresh, matching
 * the per-spawn reads of the previous inline-script implementation.
 * Undefined means no safe self-invocation exists and every guarded
 * operation fails closed.
 */
function getWorkerSelfInvocation(): SelfInvocation | undefined {
  if (cachedWorkerModulePath === null) {
    cachedWorkerModulePath = resolveWorkerModulePath();
  }
  return resolveSelfInvocation({ workerPath: cachedWorkerModulePath });
}

/** Build the worker argv: <prefix> <hidden command> <operation> <args...> */
function workerSpawnArgs(
  invocation: SelfInvocation,
  operation: string,
  ...operationArgs: string[]
): string[] {
  return [...invocation.prefixArgs, MANAGED_OUTPUT_WORKER_COMMAND, operation, ...operationArgs];
}

export interface ManagedOutputCleanupResult {
  /** Obsolete files removed, or that would be removed in dry-run mode */
  removed: string[];
  /** Mixed hook files rewritten to remove PromptScript-owned entries */
  rewritten?: string[];
  /** Managed directories pruned because they became empty */
  removedDirectories: string[];
  /**
   * True when this runtime could not resolve a safe way to run the guarded
   * worker, so cleanup was skipped and obsolete output was left in place.
   * Callers must warn and exit non-zero.
   */
  unresolvedSelfInvocation?: boolean;
}

export interface ManagedOutputCleanupOptions {
  /** Absolute base directory used to resolve formatter output paths */
  outputRoot: string;
  /** Report actions without modifying the filesystem */
  dryRun?: boolean;
}

interface DirectoryGuard {
  path: string;
  handle: FileHandle;
}

interface FileIdentity {
  dev: number | bigint;
  ino: number | bigint;
}

/**
 * Remove obsolete generated files from formatter-declared managed directories.
 *
 * Only regular files carrying a PromptScript marker are eligible. Directory
 * symlinks and file symlinks are skipped, and unmarked files are preserved.
 */
export async function cleanupManagedOutputs(
  outputs: Map<string, FormatterOutput>,
  options: ManagedOutputCleanupOptions
): Promise<ManagedOutputCleanupResult> {
  const outputRoot = resolve(options.outputRoot);
  const managedDirectories = collectManagedDirectories(outputs, outputRoot);
  const managedFiles = collectManagedFiles(outputs, outputRoot);
  const desiredFiles = collectDesiredFiles(outputs, outputRoot);
  const removed: string[] = [];
  const rewritten: string[] = [];
  const removedDirectories: string[] = [];
  let unresolvedWorker = false;
  const reportUnresolvedWorker = (): void => {
    unresolvedWorker = true;
  };

  for (const directory of managedDirectories) {
    const ancestorGuards = await openAncestorDirectories(outputRoot, directory);
    if (!ancestorGuards) continue;
    try {
      await visitDirectory(
        directory,
        desiredFiles,
        options.dryRun === true,
        removed,
        ancestorGuards,
        reportUnresolvedWorker
      );
    } finally {
      await closeDirectoryGuards(ancestorGuards);
    }
  }

  for (const file of managedFiles) {
    if (desiredFiles.has(file)) continue;
    await removeManagedFile(
      file,
      outputRoot,
      options.dryRun === true,
      removed,
      rewritten,
      reportUnresolvedWorker
    );
  }

  // Prune managed directories left empty by the removals (e.g. .github/hooks
  // after the obsolete promptscript.json is deleted). Deepest first so a
  // parent can be pruned right after its last child directory disappears.
  // Skipped entirely when nothing was removed so read-only runs never touch
  // directories the cleanup did not empty itself.
  if (removed.length > 0) {
    const prunable = managedDirectories
      .filter((directory) => removed.some((file) => isWithin(directory, file)))
      .sort((a, b) => b.length - a.length);
    const managedDirectorySet = new Set(managedDirectories);
    for (const directory of prunable) {
      await pruneEmptyDirectory(directory, outputRoot, options.dryRun === true, {
        removed,
        removedDirectories,
        managedDirectories: managedDirectorySet,
      });
    }
  }

  return {
    removed,
    ...(rewritten.length > 0 ? { rewritten } : {}),
    removedDirectories,
    ...(unresolvedWorker ? { unresolvedSelfInvocation: true } : {}),
  };
}

interface PruneTracker {
  removed: string[];
  removedDirectories: string[];
  managedDirectories: ReadonlySet<string>;
}

/**
 * Remove a directory when every entry inside it is gone (or, in dry-run mode,
 * would be gone). Returns true when the directory is (or would be) removed.
 * Never removes the output root itself or follows symlinks.
 */
async function pruneEmptyDirectory(
  directory: string,
  outputRoot: string,
  dryRun: boolean,
  tracker: PruneTracker
): Promise<boolean> {
  if (resolve(directory) === outputRoot) return false;
  const ancestorGuards = await openAncestorDirectories(outputRoot, directory);
  if (!ancestorGuards) return false;
  try {
    if (!(await directoryGuardsMatch(ancestorGuards))) return false;
    const directoryStat = await safeLstat(directory);
    if (!directoryStat?.isDirectory() || directoryStat.isSymbolicLink()) return false;
    const directoryHandle = await safeOpenDirectory(directory);
    if (!directoryHandle) return false;

    try {
      const entries = await readdir(directory, { withFileTypes: true });
      let empty = true;
      for (const entry of entries) {
        const entryPath = resolve(directory, entry.name);
        if (entry.isDirectory()) {
          if (!tracker.managedDirectories.has(entryPath)) {
            empty = false;
            continue;
          }
          if (!(await pruneEmptyDirectory(entryPath, outputRoot, dryRun, tracker))) {
            empty = false;
          }
          continue;
        }
        if (!(dryRun && tracker.removed.includes(entryPath))) {
          empty = false;
        }
      }
      if (!empty) return false;

      if (dryRun) {
        tracker.removedDirectories.push(directory);
        return true;
      }

      if (!(await directoryGuardsMatch(ancestorGuards))) return false;
      try {
        await rmdir(directory);
        tracker.removedDirectories.push(directory);
        return true;
      } catch (error: unknown) {
        // Lost a race with an external writer or the directory is already gone.
        if (isNodeError(error) && (error.code === 'ENOTEMPTY' || error.code === 'ENOENT')) {
          return false;
        }
        throw error;
      }
    } finally {
      await directoryHandle.close();
    }
  } finally {
    await closeDirectoryGuards(ancestorGuards);
  }
}

function collectManagedDirectories(
  outputs: Map<string, FormatterOutput>,
  outputRoot: string
): string[] {
  const directories = new Set<string>();

  for (const output of outputs.values()) {
    for (const directory of output.managedOutputDirectories ?? []) {
      const normalized = directory.replace(/\\/g, '/');
      if (!normalized || isAbsolute(normalized)) continue;
      if (normalized.split('/').some((segment) => segment === '..')) continue;

      const absolutePath = resolve(outputRoot, normalized);
      if (isWithin(outputRoot, absolutePath)) directories.add(absolutePath);
    }
  }

  return [...directories].sort();
}

function collectDesiredFiles(
  outputs: Map<string, FormatterOutput>,
  outputRoot: string
): Set<string> {
  const files = new Set<string>();
  for (const output of outputs.values()) {
    const absolutePath = resolve(outputRoot, output.path);
    if (isWithin(outputRoot, absolutePath)) files.add(absolutePath);
  }
  return files;
}

function collectManagedFiles(outputs: Map<string, FormatterOutput>, outputRoot: string): string[] {
  const files = new Set<string>();

  for (const output of outputs.values()) {
    for (const file of output.managedOutputFiles ?? []) {
      const normalized = file.replace(/\\/g, '/');
      if (!normalized || isAbsolute(normalized)) continue;
      if (normalized.split('/').some((segment) => segment === '..')) continue;

      const absolutePath = resolve(outputRoot, normalized);
      if (isWithin(outputRoot, absolutePath)) files.add(absolutePath);
    }
  }

  return [...files].sort();
}

async function removeManagedFile(
  file: string,
  outputRoot: string,
  dryRun: boolean,
  removed: string[],
  rewritten: string[],
  onUnresolvedWorker: () => void
): Promise<void> {
  const fileStat = await safeLstat(file);
  if (!fileStat?.isFile() || fileStat.isSymbolicLink()) return;
  const content = await readFile(file, 'utf-8');
  const prunedHooks =
    removePromptScriptOwnedHooks(file, content) ?? removePromptScriptOwnedCodexHooks(file, content);
  if (!prunedHooks && !(await isPromptScriptGenerated(file, true))) return;

  const guards = await openAncestorDirectories(outputRoot, file);
  if (!guards) return;
  try {
    if (!(await directoryGuardsMatch(guards))) return;
    if (dryRun) {
      if (!prunedHooks || prunedHooks.empty) {
        removed.push(file);
      } else {
        rewritten.push(file);
      }
      return;
    }

    const directory = dirname(file);
    const directoryStat = await safeLstat(directory);
    if (!directoryStat?.isDirectory() || directoryStat.isSymbolicLink()) return;

    if (prunedHooks && !prunedHooks.empty) {
      const didRewrite = await guardedRewrite(
        {
          directory,
          name: basename(file),
          directoryStat,
          fileStat,
          expectedContent: content,
          content: prunedHooks.content,
        },
        onUnresolvedWorker
      );
      if (didRewrite) rewritten.push(file);
      return;
    }

    if (
      await guardedUnlink(
        directory,
        basename(file),
        directoryStat,
        fileStat,
        undefined,
        onUnresolvedWorker
      )
    ) {
      removed.push(file);
    }
  } finally {
    await closeDirectoryGuards(guards);
  }
}

export async function rewriteHookOutputIfUnchanged(
  file: string,
  outputRoot: string,
  expectedContent: string,
  content: string,
  mode?: number
): Promise<boolean> {
  const root = resolve(outputRoot);
  const candidate = resolve(file);
  if (!isWithin(root, candidate)) return false;

  const fileStat = await safeLstat(candidate);
  if (!fileStat?.isFile() || fileStat.isSymbolicLink()) return false;
  const guards = await openAncestorDirectories(root, candidate);
  if (!guards) return false;
  try {
    if (!(await directoryGuardsMatch(guards))) return false;
    const directory = dirname(candidate);
    const directoryStat = await safeLstat(directory);
    if (!directoryStat?.isDirectory() || directoryStat.isSymbolicLink()) return false;

    return guardedRewrite({
      directory,
      name: basename(candidate),
      directoryStat,
      fileStat,
      expectedContent,
      content,
      mode,
    });
  } finally {
    await closeDirectoryGuards(guards);
  }
}

export async function createHookOutputSafely(
  file: string,
  outputRoot: string,
  content: string,
  mode = 0o666
): Promise<boolean> {
  const root = resolve(outputRoot);
  const candidate = resolve(file);
  if (!isWithin(root, candidate)) return false;

  const guards = await openOrCreateAncestorDirectories(root, candidate);
  if (!guards) return false;
  try {
    if (!(await directoryGuardsMatch(guards))) return false;
    const directory = dirname(candidate);
    const directoryStat = await safeLstat(directory);
    if (!directoryStat?.isDirectory() || directoryStat.isSymbolicLink()) {
      return false;
    }

    return guardedCreate(directory, basename(candidate), directoryStat, content, mode);
  } finally {
    await closeDirectoryGuards(guards);
  }
}

