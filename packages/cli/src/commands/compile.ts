/**
 * Parse target entries into compiler format.
 * Filters out targets with enabled: false.
 */
function parseTargets(targets: TargetEntry[]): { name: string; config?: TargetConfig }[] {
  return targets
    .map((entry) => {
      if (typeof entry === 'string') {
        return { name: entry };
      }
      // Object format: { github: { convention: 'xml' } }
      const entries = Object.entries(entry);
      if (entries.length === 0) {
        throw new Error('Empty target configuration');
      }
      const [name, config] = entries[0] as [string, TargetConfig | undefined];
      return { name, config };
    })
    .filter((target) => target.config?.enabled !== false);
}

function getBuildProfile(
  config: PromptScriptConfig,
  buildName: string | undefined
): BuildProfileConfig | undefined {
  if (!buildName) return undefined;

  const profile = config.builds?.[buildName];
  if (!profile) {
    const available = Object.keys(config.builds ?? {});
    const suffix =
      available.length > 0 ? ` Available build profiles: ${available.join(', ')}.` : '';
    throw new Error(`Unknown build profile: ${buildName}.${suffix}`);
  }

  return profile;
}

function resolveOutputBase(projectRoot: string, output: string | undefined): string {
  if (!output) return projectRoot;
  return isAbsolute(output) ? output : resolve(projectRoot, output);
}

function resolveProjectPath(projectRoot: string, path: string): string {
  return isAbsolute(path) ? path : resolve(projectRoot, path);
}

function validateWritePathSymlinks(outputPath: string, outputRoot: string): string | undefined {
  const root = resolve(outputRoot);
  const candidate = resolve(root, outputPath);
  const relativePath = relative(root, candidate);
  if (relativePath === '' || relativePath.startsWith('..') || isAbsolute(relativePath)) return;

  let current = root;
  for (const segment of relativePath.split(/[\\/]/)) {
    current = resolve(current, segment);
    let stat: ReturnType<typeof lstatSync> | undefined;
    try {
      stat = lstatSync(current);
    } catch (error: unknown) {
      if (
        error instanceof Error &&
        'code' in error &&
        (error as NodeJS.ErrnoException).code === 'ENOENT'
      ) {
        break;
      }
      return `Output path "${outputPath}" cannot be checked for symbolic links`;
    }
    if (stat?.isSymbolicLink()) {
      return `Output path "${outputPath}" traverses a symbolic link`;
    }
  }
  return undefined;
}

function resolveCompileConfigPath(
  projectRoot: string,
  options: Pick<CompileOptions, 'config' | 'cwd'>
): string | undefined {
  if (options.config) {
    return resolveProjectPath(projectRoot, options.config);
  }

  const environmentConfig = process.env['PROMPTSCRIPT_CONFIG'];
  if (options.cwd && environmentConfig) {
    return resolveProjectPath(projectRoot, environmentConfig);
  }

  const configPath = options.cwd ? findConfigInDir(projectRoot) : undefined;
  if (options.cwd && !configPath) {
    throw new Error(`No PromptScript configuration found in ${projectRoot}. Run: prs init`);
  }
  return configPath;
}

/**
 * Check if content was generated by PromptScript by looking for markers in the first 50 lines.
 * Extended from 20 to 50 to handle SKILL.md files with long YAML frontmatter
 * (compatibility lists, allowed-tools, etc. can push the marker past line 40).
 */
function hasPromptScriptMarker(content: string): boolean {
  const lines = content.split('\n').slice(0, 50);
  return lines.some((line) => PROMPTSCRIPT_MARKERS.some((marker) => line.includes(marker)));
}

function isPromptScriptOwnedOutput(path: string, content: string): boolean {
  if (isHookOutputPath(path)) {
    return isPromptScriptOwnedHookOutput(path, content);
  }
  return hasPromptScriptMarker(content);
}

/**
 * Read a file, returning undefined when it cannot be read.
 * Unreadable files fall through to overwrite protection.
 */
async function readFileOrUndefined(filePath: string): Promise<string | undefined> {
  try {
    return await readFile(filePath, 'utf-8');
  } catch {
    return undefined;
  }
}

/**
 * User response when prompted about overwriting a file.
 */
type OverwriteResponse = 'yes' | 'no' | 'all';

/**
 * Prompt the user about overwriting a file.
 * Returns 'yes' to overwrite this file, 'no' to skip, 'all' to overwrite all remaining.
 */
async function promptForOverwrite(
  filePath: string,
  services: CliServices
): Promise<OverwriteResponse> {
  const response = await services.prompts.select({
    message: `File exists and was not generated by PromptScript: ${filePath}\nOverwrite?`,
    choices: [
      { name: 'No (skip this file)', value: 'no' as const },
      { name: 'Yes (overwrite this file)', value: 'yes' as const },
      { name: 'All (overwrite all remaining files)', value: 'all' as const },
    ],
    default: 'no' as const,
  });
  return response;
}

