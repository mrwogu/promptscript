import { describe, expect, it } from 'vitest';
import {
  collectSkillResourcePaths,
  isGeneratedByPromptScript,
  markerStamp,
  stripFrontmatterMarkerLines,
  stripLeadingHtmlMarker,
  stripPromptScriptMarkers,
} from '../utils/markers.js';

const HTML_MARKER = '<!-- PromptScript 2026-03-22T16:36:39.660Z - do not edit -->';
const YAML_MARKER = '# promptscript-generated: 2026-03-22 | source: a.prs | target: claude';
const TYPESCRIPT_MARKER = '// promptscript-generated: opencode-plugin';
const LEGACY_TYPESCRIPT_MARKER = '// Generated by PromptScript - do not edit.';

describe('stripPromptScriptMarkers', () => {
  it('removes the HTML marker with trailing blank lines', () => {
    const content = `${HTML_MARKER}\n\n# Title`;

    expect(stripPromptScriptMarkers(content)).toBe('# Title');
  });

  it('removes the YAML marker from frontmatter', () => {
    const content = `---\n${YAML_MARKER}\nname: test\n---`;

    expect(stripPromptScriptMarkers(content)).toBe('---\nname: test\n---');
  });

  it('removes the TypeScript marker from generated plugins', () => {
    const content = `${TYPESCRIPT_MARKER}\n${LEGACY_TYPESCRIPT_MARKER}\nexport const plugin = {};`;

    expect(stripPromptScriptMarkers(content)).toBe('export const plugin = {};');
  });

  it('leaves content without markers untouched', () => {
    const content = '# Title\n\nBody';

    expect(stripPromptScriptMarkers(content)).toBe(content);
  });
});

describe('isGeneratedByPromptScript', () => {
  it('detects an HTML marker inserted after a title', () => {
    const content = `# Title\n\n${HTML_MARKER}\n\nBody`;

    expect(isGeneratedByPromptScript(content)).toBe(true);
  });

  it('detects a YAML marker inside frontmatter', () => {
    const content = `---\n${YAML_MARKER}\nname: test\n---\n\nBody`;

    expect(isGeneratedByPromptScript(content)).toBe(true);
  });

  it('detects a TypeScript marker in a generated plugin', () => {
    expect(isGeneratedByPromptScript(`${TYPESCRIPT_MARKER}\nexport const plugin = {};`)).toBe(true);
    expect(
      isGeneratedByPromptScript(`${LEGACY_TYPESCRIPT_MARKER}\nexport const plugin = {};`)
    ).toBe(true);
  });

  it('ignores a marker quoted deep inside prose', () => {
    const content = `# Title\n\n${'filler\n'.repeat(10)}${HTML_MARKER}`;

    expect(isGeneratedByPromptScript(content)).toBe(false);
  });

  it('returns false for hand written content', () => {
    expect(isGeneratedByPromptScript('---\nname: test\n---\n\nBody')).toBe(false);
  });
});

describe('stripFrontmatterMarkerLines', () => {
  it('removes marker lines and keeps the remaining fields', () => {
    const frontmatter = `${YAML_MARKER}\nname: demo\ndescription: x`;

    expect(stripFrontmatterMarkerLines(frontmatter)).toBe('name: demo\ndescription: x');
  });

  it('keeps regular YAML comments', () => {
    const frontmatter = '# hand written note\nname: demo';

    expect(stripFrontmatterMarkerLines(frontmatter)).toBe(frontmatter);
  });
});

describe('stripLeadingHtmlMarker', () => {
  it('removes a marker at the top of the body', () => {
    const body = `${HTML_MARKER}\n\n# Demo`;

    expect(stripLeadingHtmlMarker(body)).toBe('# Demo');
  });

  it('keeps markers documented inside prose', () => {
    const body = `# Demo\n\nGenerated files start with ${HTML_MARKER}`;

    expect(stripLeadingHtmlMarker(body)).toBe(body);
  });
});

describe('markerStamp', () => {
  it('writes the word static in static mode', () => {
    expect(markerStamp('static', '1700000000')).toBe('static');
  });

  it('uses SOURCE_DATE_EPOCH seconds in timestamp mode', () => {
    expect(markerStamp('timestamp', ' 1700000000 ')).toBe('2023-11-14T22:13:20.000Z');
  });

  it('falls back to the clock for a missing or invalid epoch', () => {
    expect(markerStamp('timestamp')).toMatch(/^\d{4}-\d{2}-\d{2}T/);
    expect(markerStamp('timestamp', '-5')).toMatch(/^\d{4}-\d{2}-\d{2}T/);
  });

  it('keeps a static marker detectable and strippable', () => {
    const marker = `<!-- PromptScript ${markerStamp('static')} | source: a.prs | target: claude - do not edit -->`;
    expect(isGeneratedByPromptScript(`${marker}\n# Title\n`)).toBe(true);
    expect(stripPromptScriptMarkers(`${marker}\n\nBody\n`)).toBe('Body\n');
  });
});

describe('collectSkillResourcePaths', () => {
  it('maps files in a skill directory to their skill file', () => {
    const resources = collectSkillResourcePaths([
      'CLAUDE.md',
      '.claude/skills/a/SKILL.md',
      '.claude/skills/a/templates/report.md',
      '.claude/skills/a/scripts/run.sh',
      '.claude/skills/ab/SKILL.md',
      '.claude/agents/reviewer.md',
    ]);
    expect([...resources.entries()]).toEqual([
      ['.claude/skills/a/templates/report.md', '.claude/skills/a/SKILL.md'],
      ['.claude/skills/a/scripts/run.sh', '.claude/skills/a/SKILL.md'],
    ]);
  });

  it('gives a nested skill its own files', () => {
    const resources = collectSkillResourcePaths([
      'skills/outer/SKILL.md',
      'skills/outer/inner/skill.md',
      'skills/outer/inner/data.txt',
      'skills/outer/data.txt',
    ]);
    expect(resources.get('skills/outer/inner/data.txt')).toBe('skills/outer/inner/skill.md');
    expect(resources.get('skills/outer/data.txt')).toBe('skills/outer/SKILL.md');
    expect(resources.has('skills/outer/inner/skill.md')).toBe(false);
  });

  it('ignores a skill file at the output root', () => {
    expect(collectSkillResourcePaths(['SKILL.md', 'README.md']).size).toBe(0);
  });
});
