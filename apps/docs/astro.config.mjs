// The live compile widget bundles @promptscript/browser-compiler for the
// browser. Like the playground, it needs fs and path shims, but only in the
// client bundle: Astro itself still runs on real Node modules.
const browserShims = {
  name: 'promptscript-browser-shims',
  enforce: 'pre',
  resolveId(id, _importer, options) {
    if (options?.ssr) return null;
    if (id === 'fs') {
      return fileURLToPath(
        new URL('../../packages/browser-compiler/src/shims/fs.ts', import.meta.url)
      );
    }
    if (id === 'path') return this.resolve('path-browserify');
    return null;
  },
};

const promptscriptGrammar = {
  ...JSON.parse(
    readFileSync(
      new URL('../vscode/syntaxes/promptscript.tmLanguage.json', import.meta.url),
      'utf-8'
    )
  ),
  name: 'promptscript',
  aliases: ['prs'],
};

const lastModified = gitLastModified();

// Starlight's autogenerate only sees files under src/content/docs, and ours
// live in docs/. So autogenerated groups are listed here from frontmatter,
// sorted like autogenerate does: sidebar.order first, then label.
function autogeneratedItems(directory) {
  const dir = new URL(`../../docs/${directory}/`, import.meta.url);
  return readdirSync(dir)
    .filter((file) => file.endsWith('.md'))
    .map((file) => {
      const frontmatter = readFileSync(new URL(file, dir), 'utf-8').split('\n---')[0];
      const field = (name) =>
        new RegExp(`^\\s*${name}:\\s*(.+)$`, 'm')
          .exec(frontmatter)?.[1]
          .replace(/^['"]|['"]$/g, '');
      return {
        slug: docIdFromEntry(`${directory}/${file}`),
        label: field('label') ?? field('title'),
        order: Number(field('order') ?? Number.MAX_SAFE_INTEGER),
      };
    })
    .sort((a, b) => a.order - b.order || a.label.localeCompare(b.label))
    .map(({ slug, label }) => ({ slug, label }));
}

const sidebar = SIDEBAR.map((group) => ({
  ...group,
  items: group.items.flatMap((item) =>
    item.autogenerate ? autogeneratedItems(item.autogenerate.directory) : [item]
  ),
}));

